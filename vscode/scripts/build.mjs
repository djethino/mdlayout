// Prépare l'extension avant son emballage (`vsce package` appelle `vscode:prepublish`) : le greffon copié depuis
// `packages/mdlayout/src` (une seule source, jamais modifiée ici) et sa feuille de base écrite en fichier, que l'aperçu
// charge par `markdown.previewStyles`. Rien n'est téléchargé.
import { cpSync, existsSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(dirname(fileURLToPath(import.meta.url)));
// La bibliothèque : `packages/mdlayout/src` dans DecisionRoxor, `src/` à la racine du dépôt public (l'extension y est
// dans `vscode/`, `scripts/mdlayout-public.mjs`).
const source = [join(here, "..", "mdlayout", "src"), join(here, "..", "src")].find((dir) => existsSync(join(dir, "index.js")));
if (!source) throw new Error("mdlayout: the library (src/index.js) was not found next to the extension");
const copy = join(here, "mdlayout");

rmSync(copy, { recursive: true, force: true });
cpSync(source, copy, { recursive: true, filter: (path) => !path.endsWith(".d.ts") });
// Le dossier copié est un module ES ; l'extension, elle, reste en CommonJS.
writeFileSync(join(copy, "package.json"), '{ "type": "module" }\n');

const { generateBaseCSS, generatePageCSS } = await import(pathToFileURL(join(copy, "index.js")).href);
mkdirSync(join(here, "media"), { recursive: true });
writeFileSync(join(here, "media", "mdlayout.css"), `/* mdlayout — generated by scripts/build.mjs, do not edit. */\n${generateBaseCSS()}\n${generatePageCSS()}\n`);
console.log("mdlayout copied, media/mdlayout.css written");
